    static func find(in text: String) -> [String] {
        let pattern = #"(?<![\p{L}\d])((?:[123]\s*)?[A-Za-z][A-Za-z ]{0,20}?)\.?\s*(\d{1,3})(?:\s*[:.v]\s*(\d{1,3})(?:\s*[-–—]\s*(\d{1,3})(?:[:.](\d{1,3}))?)?)?(?![\p{L}\d])"#
        guard let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive]) else { return [] }
        return regex.matches(in: text, range: NSRange(text.startIndex..., in: text)).compactMap { match in
            func group(_ index: Int) -> String? {
                Range(match.range(at: index), in: text).map { String(text[$0]) }
            }
            guard let rawBook = group(1), let chapter = group(2) else { return nil }
            let words = rawBook.split(separator: " ")
            var bookName: String?
            for index in words.indices {
                if let name = books[words[index...].joined().lowercased()] { bookName = name; break }
            }
            guard let bookName else { return nil }
            var result = bookName + " " + chapter
            if let verse = group(3) { result += ":" + verse }
            if let end = group(4) { result += "-" + end }
            if let endVerse = group(5) { result += ":" + endVerse }
            return result
        }
    }
